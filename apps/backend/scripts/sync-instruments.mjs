import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const MASTER_URL = process.env.ANGELONE_MASTER_URL ?? "https://margincalculator.angelbroking.com/OpenAPI_File/files/OpenAPIScripMaster.json";
const NSE_URL = "https://archives.nseindia.com/content/equities/EQUITY_L.csv";
const BSE_URL = "https://api.bseindia.com/BseIndiaAPI/api/ListofScripData/w?Group=&Scripcode=&segment=Equity&Status=Active";
const NSE_SERIES = new Set(["EQ", "BE", "BZ"]);

const Q = String.fromCharCode(34);

function parseCsv(text) {
  const rows = [];
  for (const line of text.split(/\r?\n/)) {
    if (!line) continue;
    const out = [];
    let cur = "";
    let quoted = false;
    for (let i = 0; i < line.length; i += 1) {
      const char = line[i];
      if (quoted) {
        if (char === Q) { if (line[i + 1] === Q) { cur += Q; i += 1; } else quoted = false; }
        else cur += char;
      } else if (char === Q) quoted = true;
      else if (char === ",") { out.push(cur); cur = ""; }
      else cur += char;
    }
    out.push(cur);
    rows.push(out);
  }
  return rows;
}

function normalizeName(value) { return String(value ?? "").replace(/\s+/g, " ").trim(); }

const master = await (await fetch(MASTER_URL)).json();
if (!Array.isArray(master)) throw new Error("Angel One instrument master did not return an array");

const nseCsv = await (await fetch(NSE_URL, { headers: { "User-Agent": "Mozilla/5.0" } })).text();
const nseRows = parseCsv(nseCsv).slice(1).filter((row) => row.length >= 3 && NSE_SERIES.has((row[2] ?? "").trim()));

const bseResponse = await fetch(BSE_URL, { headers: { "User-Agent": "Mozilla/5.0", Referer: "https://www.bseindia.com/", Origin: "https://www.bseindia.com", Accept: "application/json" } });
if (!bseResponse.ok) throw new Error(`BSE equity list request failed: ${bseResponse.status}`);
const bseRows = await bseResponse.json();

const angelNse = new Map();
for (const row of master) if (row.exch_seg === "NSE") angelNse.set(String(row.symbol).toUpperCase(), row);
const angelBse = new Map();
for (const row of master) if (row.exch_seg === "BSE") angelBse.set(String(row.token), row);

const instruments = [];
const nseOmitted = [];
for (const row of nseRows) {
  const symbol = (row[0] ?? "").trim().toUpperCase();
  if (!symbol) continue;
  const candidate = ["-EQ", "-BE", "-BZ", ""].map((suffix) => angelNse.get(symbol + suffix)).find(Boolean);
  if (!candidate) { nseOmitted.push(symbol); continue; }
  instruments.push({ exchange: "NSE", exchangeType: 1, token: String(candidate.token), symbol, tradingSymbol: String(candidate.symbol), name: normalizeName(row[1]), isin: (row[6] ?? "").trim() || undefined, type: "EQUITY" });
}

const bseOmitted = [];
for (const row of bseRows) {
  const angel = angelBse.get(String(row.SCRIP_CD));
  const symbol = String(row.scrip_id ?? row.Scrip_Name ?? "").trim().toUpperCase();
  if (!angel || !symbol) { bseOmitted.push(symbol || String(row.SCRIP_CD)); continue; }
  instruments.push({ exchange: "BSE", exchangeType: 3, token: String(row.SCRIP_CD), symbol, tradingSymbol: String(angel.symbol), name: normalizeName(row.Issuer_Name), isin: String(row.ISIN_NUMBER ?? "").trim() || undefined, type: "EQUITY" });
}

instruments.sort((a, b) => (a.exchange === b.exchange ? a.symbol.localeCompare(b.symbol) : a.exchange.localeCompare(b.exchange)));

const nseIncluded = instruments.filter((instrument) => instrument.exchange === "NSE").length;
const bseIncluded = instruments.filter((instrument) => instrument.exchange === "BSE").length;
const header = "// GENERATED by scripts/sync-instruments.mjs - do not edit by hand.\nimport type { InstrumentSearchResult } from \"@market-watch/shared-types\";\n\nexport const generatedAt = " + JSON.stringify(new Date().toISOString()) + ";\n\nexport const instruments: InstrumentSearchResult[] = ";
const body = JSON.stringify(instruments, null, 2);
const output = `${header}${body};\n`;
const target = fileURLToPath(new URL("../src/instruments/instruments.generated.ts", import.meta.url));
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, output);

console.log("Universe: NSE/BSE listed cash-market equities with an Angel One market-data token");
console.log(`NSE source equities: ${nseRows.length}  included: ${nseIncluded}  omitted (no Angel token): ${nseOmitted.length}`);
if (nseOmitted.length) console.log(`NSE omitted sample: ${nseOmitted.slice(0, 20).join(", ")}`);
console.log(`BSE source equities: ${bseRows.length}  included: ${bseIncluded}  omitted (no Angel token): ${bseOmitted.length}`);
if (bseOmitted.length) console.log(`BSE omitted sample: ${bseOmitted.slice(0, 20).join(", ")}`);
console.log(`Total instruments: ${instruments.length}  snapshot bytes: ${Buffer.byteLength(output, "utf8")}`);
